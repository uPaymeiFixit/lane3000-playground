"""A maze that runs on the Lane/3000 by itself, using RBA's built-in script language.

STATUS: does not work on our unit. Its app is Unified Payment Platform 6.80.09, which ACKs
26.x Run Script and then ignores it (same as an undefined message), even for a missing file.
Kept for terminals running classic RBA, where the guide says 26.x is supported.

RBA scripts (26.x Run Script, guide Appendix B) are state machines: each [tag] is a screen
(a form plus label text), and each button either jumps to another tag, shows/hides a button,
or ends the script with a key code. No variables, counters or timers.

This generator turns a maze into one tag per open square. The arrow keys jump to the
neighbouring square's tag (or back to the same tag when there is a wall). The host only
uploads the script and sends one 26.x message; after that the terminal plays it alone.

    python3 maze_script.py --install-form   # once: upload MAZE.K3Z and reboot
    python3 maze_script.py                  # upload MAZE.TXT, start it, wait for the result
    python3 maze_script.py --detach         # start it and exit immediately (the Mac can go away)
    python3 maze_script.py --print          # just print the generated script
"""

import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lane import Lane  # noqa: E402

MAZE = [
    "###########",
    "#@..#.....#",
    "#.#.#.###.#",
    "#.#...#...#",
    "#.#####.#.#",
    "#.......#E#",
    "###########",
]
MOVES = {"L": (-1, 0), "U": (0, -1), "D": (0, 1), "R": (1, 0)}


def _label(lid, y, h, size, color, mono=True):
    family = "monospace" if mono else "sans-serif"
    return (f'<Label x="0" y="{y}" width="320" height="{h}" id="{lid}" align="center" background="false" '
            f'border="false" backgroundcolor="000000" bordercolor="000000" fontsize="{size}px" '
            f'fontweight="bold" fontfamily="{family}" text="&lt;?iv{lid}?&gt;" textcolor="{color}" '
            'textsource="custom" textwrap="false" />')


def _button(letter):
    # HTML id and returned button id are both the letter, so the script can name it either way.
    return (f'<BmpButton x="0" y="0" width="1" height="1" id="{letter}" key="CUSTOM" buttonid="\'{letter}\'" '
            'upimage="GAMEBTN.PNG" hostupimage=".\\GAMEBTN.PNG" downimage="GAMEBTN.PNG" '
            'hostdownimage=".\\GAMEBTN.PNG" textsource="custom" buttontext=" " textoffsetx="0" '
            'textoffsety="0" textcolor="000000" fontsize="10px" fontweight="normal" fontfamily="sans-serif" '
            'align="center" eventfireon="down" visibility="visible" tonetype="1" />')


FORM = "\n".join(
    ['<Form id="Form" terminalname="Lane 3000" designerversion="1.0" x="0" y="0" width="320" height="240" '
     'template="TEMPMENU.HTM" backgroundcolor="101828" timeout="0" enterenabled="true" entertone="1" '
     'clearenabled="false" cleartone="0" cancelenabled="true" canceltone="1" tonetype="0" '
     'f1enabled="true" f2enabled="true" f3enabled="true" f4enabled="true" '
     'F1-link="L" F2-link="U" F3-link="D" F4-link="R" '
     'swledbarenabled="false" headerenabled="false" clesslogo="false" windowtype="full" />',
     _label("TITLE", 2, 30, 18, "ffdc00", mono=False)]
    + [_label(f"ROW{i}", 34 + i * 25, 25, 22, "c8ffc8") for i in range(len(MAZE))]
    + [_label("HINT", 214, 24, 13, "a0a0b4", mono=False)]
    + [_button(k) for k in MOVES]
) + "\n"


def tag(x, y):
    return f"c{x}_{y}"


def build_script():
    cells = [(x, y) for y, row in enumerate(MAZE) for x, c in enumerate(row) if c != "#"]
    start = next((x, y) for y, row in enumerate(MAZE) for x, c in enumerate(row) if c == "@")
    goal = next((x, y) for y, row in enumerate(MAZE) for x, c in enumerate(row) if c == "E")
    clean = [row.replace("@", ".") for row in MAZE]
    cells.remove(start)
    out = ["// MAZE.TXT - generated by maze_script.py; one tag per open square"]
    for (x, y) in [start] + cells:
        grid = [list(r) for r in clean]
        grid[y][x] = "@"
        won = (x, y) == goal
        out.append(f"[{'start' if (x, y) == start else tag(x, y)}]")
        out.append("form=MAZE.K3Z")
        out.append('text=TITLE,"YOU ESCAPED!"' if won else 'text=TITLE,"Find the exit E"')
        for i, row in enumerate(grid):
            out.append(f'text=ROW{i},"{"".join(row)}"')
        out.append('text=HINT,"any key to finish"' if won else 'text=HINT,"arrows move - RED quits"')
        if won:
            continue  # no button parameters: any key ends the script and reports it
        for key, (dx, dy) in MOVES.items():
            nx, ny = x + dx, y + dy
            dest = (nx, ny) if MAZE[ny][nx] != "#" else (x, y)
            out.append(f"button={key},[{'start' if dest == start else tag(*dest)}]")
    return "\n".join(out) + "\n"


def install_form():
    from game_screen import wait_for_terminal
    with Lane() as lane:
        lane.soft_reset()
        if not lane.read_binary("/HOST/GAMEBTN.PNG"):
            raise SystemExit("GAMEBTN.PNG missing - run `python3 game_screen.py --install` first")
        lane.write_file("MAZE.K3Z", FORM.encode("latin-1"))
        print("Uploaded MAZE.K3Z - rebooting terminal...")
        lane.send("97.")
    print("Back:", wait_for_terminal()[:2])


RESULTS = {"0": "script complete", "1": "form not found", "2": "text file not found",
           "3": "script not found", "4": "error parsing script file", "5": "tag not found"}


def run(detach=False):
    script = build_script()
    with Lane() as lane:
        lane.soft_reset()
        lane.write_file("MAZE.TXT", script.encode("latin-1"))
        print(f"Uploaded MAZE.TXT ({len(script)} bytes, {script.count('[')} screens); starting it.")
        # Scripts don't start while the terminal is offline ("This Lane Closed", e.g. after a reboot).
        # 01.00000000 = go online keeping the current program/parameter versions.
        lane.request("01.00000000", "01.", 5)
        lane.send("26.MAZE.TXT")
        if detach:
            print("Started. The terminal is on its own now.")
            return
        r = lane.recv("26.", 3600)
        if r:
            key = r[4:5]
            print("Result:", RESULTS.get(r[3], r[3]), "| key:", repr(key) if r[3] == "0" else "-")


if __name__ == "__main__":
    if "--print" in sys.argv:
        print(build_script())
    elif "--install-form" in sys.argv:
        install_form()
    else:
        run(detach="--detach" in sys.argv)
