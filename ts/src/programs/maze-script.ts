/**
 * A maze that runs on the Lane/3000 by itself, using RBA's built-in script language.
 *
 * STATUS: does not work on our unit. Its app is Unified Payment Platform 6.80.09, which ACKs
 * 26.x Run Script and then ignores it (same as an undefined message), even for a missing file.
 * Kept for terminals running classic RBA, where the guide says 26.x is supported.
 *
 * RBA scripts (26.x Run Script, guide Appendix B) are state machines: each [tag] is a screen
 * (a form plus label text), and each button either jumps to another tag, shows/hides a button,
 * or ends the script with a key code. No variables, counters or timers.
 */

import { LaneError } from "../protocol/lane.js";
import { waitForTerminal, withLane } from "../protocol/serial.js";
import { chars, pyRepr, pyReprList } from "../util/py-repr.js";

export const USAGE = `A maze that runs on the Lane/3000 by itself, using RBA's built-in script language.
(Does NOT run on our unit: no 26.x support. Kept as a record of the attempt.)

    bun run maze-script --install-form   # once: upload MAZE.K3Z and reboot
    bun run maze-script                     # upload MAZE.TXT, start it, wait for the result
    bun run maze-script --detach         # start it and exit immediately (the Mac can go away)
    bun run maze-script --print          # just print the generated script`;

export const MAZE: readonly string[] = [
  "###########",
  "#@..#.....#",
  "#.#.#.###.#",
  "#.#...#...#",
  "#.#####.#.#",
  "#.......#E#",
  "###########",
];

type MoveKey = "L" | "U" | "D" | "R";
const MOVES: readonly (readonly [MoveKey, number, number])[] = [
  ["L", -1, 0],
  ["U", 0, -1],
  ["D", 0, 1],
  ["R", 1, 0],
];

function label(lid: string, y: number, h: number, size: number, color: string, mono = true): string {
  const family = mono ? "monospace" : "sans-serif";
  return (
    `<Label x="0" y="${y}" width="320" height="${h}" id="${lid}" align="center" background="false" ` +
    `border="false" backgroundcolor="000000" bordercolor="000000" fontsize="${size}px" ` +
    `fontweight="bold" fontfamily="${family}" text="&lt;?iv${lid}?&gt;" textcolor="${color}" ` +
    'textsource="custom" textwrap="false" />'
  );
}

function button(letter: string): string {
  // HTML id and returned button id are both the letter, so the script can name it either way.
  return (
    `<BmpButton x="0" y="0" width="1" height="1" id="${letter}" key="CUSTOM" buttonid="'${letter}'" ` +
    'upimage="GAMEBTN.PNG" hostupimage=".\\GAMEBTN.PNG" downimage="GAMEBTN.PNG" ' +
    'hostdownimage=".\\GAMEBTN.PNG" textsource="custom" buttontext=" " textoffsetx="0" ' +
    'textoffsety="0" textcolor="000000" fontsize="10px" fontweight="normal" fontfamily="sans-serif" ' +
    'align="center" eventfireon="down" visibility="visible" tonetype="1" />'
  );
}

export const FORM =
  [
    '<Form id="Form" terminalname="Lane 3000" designerversion="1.0" x="0" y="0" width="320" height="240" ' +
      'template="TEMPMENU.HTM" backgroundcolor="101828" timeout="0" enterenabled="true" entertone="1" ' +
      'clearenabled="false" cleartone="0" cancelenabled="true" canceltone="1" tonetype="0" ' +
      'f1enabled="true" f2enabled="true" f3enabled="true" f4enabled="true" ' +
      'F1-link="L" F2-link="U" F3-link="D" F4-link="R" ' +
      'swledbarenabled="false" headerenabled="false" clesslogo="false" windowtype="full" />',
    label("TITLE", 2, 30, 18, "ffdc00", false),
    ...MAZE.map((_, i) => label(`ROW${i}`, 34 + i * 25, 25, 22, "c8ffc8")),
    label("HINT", 214, 24, 13, "a0a0b4", false),
    ...MOVES.map(([k]) => button(k)),
  ].join("\n") + "\n";

function tag(x: number, y: number): string {
  return `c${x}_${y}`;
}

function at(x: number, y: number): string {
  return MAZE[y]?.charAt(x) ?? "#";
}

function find(ch: string): readonly [number, number] {
  for (const [y, row] of MAZE.entries()) {
    const x = row.indexOf(ch);
    if (x >= 0) return [x, y];
  }
  throw new LaneError(`maze has no ${ch}`);
}

export function buildScript(): string {
  const cells: (readonly [number, number])[] = [];
  MAZE.forEach((row, y) => {
    chars(row).forEach((c, x) => {
      if (c !== "#") cells.push([x, y]);
    });
  });
  const [sx, sy] = find("@");
  const [gx, gy] = find("E");
  const clean = MAZE.map((row) => row.replaceAll("@", "."));
  const others = cells.filter(([x, y]) => !(x === sx && y === sy));
  const isStart = (x: number, y: number): boolean => x === sx && y === sy;
  const out = ["// MAZE.TXT - generated by maze_script.py; one tag per open square"];
  const startCell: readonly [number, number] = [sx, sy];
  for (const [x, y] of [startCell, ...others]) {
    const grid = clean.map(chars);
    const row = grid[y];
    if (row !== undefined) row[x] = "@";
    const won = x === gx && y === gy;
    out.push(`[${isStart(x, y) ? "start" : tag(x, y)}]`);
    out.push("form=MAZE.K3Z");
    out.push(won ? 'text=TITLE,"YOU ESCAPED!"' : 'text=TITLE,"Find the exit E"');
    grid.forEach((r, i) => out.push(`text=ROW${i},"${r.join("")}"`));
    out.push(won ? 'text=HINT,"any key to finish"' : 'text=HINT,"arrows move - RED quits"');
    if (won) continue; // no button parameters: any key ends the script and reports it
    for (const [key, dx, dy] of MOVES) {
      const nx = x + dx;
      const ny = y + dy;
      const [destX, destY] = at(nx, ny) !== "#" ? [nx, ny] : [x, y];
      out.push(`button=${key},[${isStart(destX, destY) ? "start" : tag(destX, destY)}]`);
    }
  }
  return out.join("\n") + "\n";
}

async function installForm(): Promise<void> {
  await withLane(async (lane) => {
    await lane.softReset();
    const btn = await lane.readBinary("/HOST/GAMEBTN.PNG");
    if (btn === null || btn.length === 0) {
      throw new LaneError("GAMEBTN.PNG missing - run `bun run game-screen --install` first");
    }
    await lane.writeFile("MAZE.K3Z", Buffer.from(FORM, "latin1"));
    console.log("Uploaded MAZE.K3Z - rebooting terminal...");
    await lane.send("97.");
  });
  console.log("Back:", pyReprList((await waitForTerminal()).slice(0, 2)));
}

const RESULTS: Readonly<Record<string, string>> = {
  "0": "script complete",
  "1": "form not found",
  "2": "text file not found",
  "3": "script not found",
  "4": "error parsing script file",
  "5": "tag not found",
};

async function run(detach: boolean): Promise<void> {
  const script = buildScript();
  await withLane(async (lane) => {
    await lane.softReset();
    await lane.writeFile("MAZE.TXT", Buffer.from(script, "latin1"));
    console.log(
      `Uploaded MAZE.TXT (${script.length} bytes, ${script.split("[").length - 1} screens); starting it.`,
    );
    // Scripts don't start while the terminal is offline ("This Lane Closed", e.g. after a reboot).
    // 01.00000000 = go online keeping the current program/parameter versions.
    await lane.request("01.00000000", 5000);
    await lane.send("26.MAZE.TXT");
    if (detach) {
      console.log("Started. The terminal is on its own now.");
      return;
    }
    const r = await lane.recv("26", 3600_000);
    if (r !== null) {
      const status = r.body.slice(0, 1);
      const key = r.body.slice(1, 2);
      console.log("Result:", RESULTS[status] ?? status, "| key:", status === "0" ? pyRepr(key) : "-");
    }
  });
}

export async function main(args: readonly string[]): Promise<number> {
  if (args.includes("--help")) {
    console.log(USAGE);
    return 0;
  }
  if (args.includes("--print")) {
    console.log(buildScript());
    return 0;
  }
  if (args.includes("--install-form")) {
    await installForm();
    return 0;
  }
  await run(args.includes("--detach"));
  return 0;
}
